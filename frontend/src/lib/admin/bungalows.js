/** Bungalov DTO'sundan PUT gövdesi (yerinde küçük güncellemeler için) */
export function bungalowToInput(b) {
    return {
        slug: b.slug,
        regionId: b.region?.id ?? null,
        title: b.title,
        description: b.description,
        longDescription: b.longDescription,
        location: b.location,
        image: b.image,
        gallery: b.gallery ?? [],
        breakfastIncluded: b.breakfastIncluded,
        breakfastNote: b.breakfastNote,
        breakfastCard: b.breakfastCard,
        capacity: b.capacity,
        amenities: b.amenities ?? [],
        featureStrip: b.featureStrip ?? [],
        detailedAmenities: b.detailedAmenities ?? [],
        distances: b.distances ?? [],
        locationNote: b.locationNote,
        rules: b.rules ?? [],
        ratingLabel: b.ratingLabel,
        ratingScore: b.ratingScore,
        ratingCount: b.ratingCount,
        seoTitle: b.seoTitle,
        seoDescription: b.seoDescription,
        seoKeywords: b.seoKeywords,
        ogImage: b.ogImage,
        defaultPricePerNight: b.defaultPricePerNight,
        currency: b.currency,
        isFeatured: b.isFeatured,
        isActive: b.isActive,
        orderIndex: b.orderIndex,
    };
}